/**
 * Writes src/components/home/districtMap.ts: mainland Portugal's 18 districts as SVG paths,
 * for the home page's background map. Reads the simplified CAOP boundaries already in the
 * database (area_boundaries, CAOP 2025, DGT, CC BY 4.0), projects them (equirectangular, scaled
 * for latitude 39.5°), simplifies them further and rounds them to one decimal.
 *
 * Run from apps/web after a new CAOP import: node scripts/district-map.mjs
 */
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const require = createRequire(import.meta.url);
const Database = require("better-sqlite3");

const here = path.dirname(fileURLToPath(import.meta.url));
const dbPath =
  process.env.DATABASE_PATH ?? path.join(here, "../../../data/observatorio-habitacao.db");
const out = path.join(here, "../src/components/home/districtMap.ts");

/** Map height in SVG units; the width follows from the projection. */
const HEIGHT = 600;
/** Douglas–Peucker tolerance in SVG units. */
const TOLERANCE = 0.6;

const db = new Database(dbPath, { readonly: true });
const rows = db
  .prepare(
    `select a.code, a.name, b.geometry from areas a join area_boundaries b on b.area_id = a.id
     where a.level = 'district' and a.code is not null order by a.code`,
  )
  .all();
if (rows.length !== 18) throw new Error(`expected 18 mainland districts, found ${rows.length}`);

const polygons = (g) => (g.type === "Polygon" ? [g.coordinates] : g.coordinates);
const all = rows.flatMap((r) => polygons(JSON.parse(r.geometry)).flat(3));
const lngs = all.filter((_, i) => i % 2 === 0);
const lats = all.filter((_, i) => i % 2 === 1);
const [minLng, maxLng, minLat, maxLat] = [
  Math.min(...lngs),
  Math.max(...lngs),
  Math.min(...lats),
  Math.max(...lats),
];
const kx = Math.cos((39.5 * Math.PI) / 180);
const scale = HEIGHT / (maxLat - minLat);
const width = Math.ceil((maxLng - minLng) * kx * scale);
const project = ([lng, lat]) => [(lng - minLng) * kx * scale, (maxLat - lat) * scale];

function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const [a, b] = [points[0], points[points.length - 1]];
  let max = 0;
  let index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const d = distance(points[i], a, b);
    if (d > max) [max, index] = [d, i];
  }
  if (max <= tolerance) return [a, b];
  return [
    ...simplify(points.slice(0, index + 1), tolerance).slice(0, -1),
    ...simplify(points.slice(index), tolerance),
  ];
}

function distance([x, y], [x1, y1], [x2, y2]) {
  const dx = x2 - x1;
  const dy = y2 - y1;
  const len = dx * dx + dy * dy;
  const t = len ? Math.max(0, Math.min(1, ((x - x1) * dx + (y - y1) * dy) / len)) : 0;
  return Math.hypot(x - (x1 + t * dx), y - (y1 + t * dy));
}

const r1 = (v) => Math.round(v * 10) / 10;
const districts = rows.map((r) => {
  const d = polygons(JSON.parse(r.geometry))
    .map((poly) => poly[0]) // outer rings only: no district has holes worth drawing
    .map((ring) => simplify(ring.map(project), TOLERANCE))
    .filter((ring) => ring.length >= 4)
    .map((ring) => "M" + ring.map(([x, y]) => `${r1(x)} ${r1(y)}`).join("L") + "Z")
    .join("");
  return { code: r.code, name: r.name, d };
});

const body = `// Generated by scripts/district-map.mjs from CAOP 2025 (DGT, CC BY 4.0). Do not edit.

/** Mainland Portugal's districts as SVG paths, in a ${width} × ${HEIGHT} view box. */
export const DISTRICT_MAP = {
  width: ${width},
  height: ${HEIGHT},
  districts: ${JSON.stringify(districts, null, 2)},
} as const;
`;
writeFileSync(out, body);
console.log(`${out}: ${districts.length} districts, ${width}×${HEIGHT}, ${body.length} bytes`);
