/**
 * The home page's report preview (issue #9): the example's PDF report (the T1 in Braga, made by
 * the dev server's /api/dev/example-report) in Portuguese and English, with each page as an
 * image, large for the viewer and small for the fanned sheets.
 *
 *   npm run dev            (in another terminal)
 *   node scripts/report-preview.mjs
 *
 * Writes public/relatorio-exemplo/{pt,en}/ and src/components/home/reportPreview.ts. Run it
 * again when the report's layout or the example changes.
 */
import { createCanvas } from "@napi-rs/canvas";
import { getDocument } from "pdfjs-dist/legacy/build/pdf.mjs";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const DEV_URL = process.env.DEV_URL ?? "http://100.93.94.115:3100";
const OUT = path.resolve("public/relatorio-exemplo");
const SIZES = { large: { scale: 1.6, quality: 74 }, small: { scale: 0.62, quality: 80 } };
const fonts = path.join(
  path.dirname(createRequire(import.meta.url).resolve("pdfjs-dist/package.json")),
  "standard_fonts/",
);

const manifest = {};
for (const locale of ["pt", "en"]) {
  const response = await fetch(`${DEV_URL}/api/dev/example-report?lang=${locale}`);
  if (!response.ok)
    throw new Error(`${locale}: HTTP ${response.status} (is the dev server running?)`);
  const pdf = new Uint8Array(await response.arrayBuffer());
  const dir = path.join(OUT, locale);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  writeFileSync(path.join(dir, "relatorio-exemplo.pdf"), pdf);

  const doc = await getDocument({ data: pdf.slice(), standardFontDataUrl: fonts }).promise;
  for (let n = 1; n <= doc.numPages; n++) {
    const page = await doc.getPage(n);
    for (const [size, { scale, quality }] of Object.entries(SIZES)) {
      const viewport = page.getViewport({ scale });
      const canvas = createCanvas(Math.ceil(viewport.width), Math.ceil(viewport.height));
      await page.render({ canvas, canvasContext: canvas.getContext("2d"), viewport }).promise;
      writeFileSync(
        path.join(dir, `pagina-${n}-${size}.webp`),
        await canvas.encode("webp", quality),
      );
    }
  }
  manifest[locale] = { pages: doc.numPages, pdfKb: Math.round(pdf.length / 1024) };
  console.log(`${locale}: ${doc.numPages} pages, ${manifest[locale].pdfKb} KB`);
}

writeFileSync(
  path.resolve("src/components/home/reportPreview.ts"),
  `// Generated by scripts/report-preview.mjs: the example report's pages and size, per language.\n` +
    `export const REPORT_PREVIEW = ${JSON.stringify(manifest)} as const;\n`,
);
